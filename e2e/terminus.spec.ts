import { expect, test } from "@playwright/test";

const line = { id: "c1", name: "Test", termini: [{ id: "a", kind: "terminus", name: "Départ", coordinates: [6.12, 45.9] }, { id: "z", kind: "terminus", name: "Arrivée", coordinates: [6.13, 45.9] }], passages: [], arrets: [{ id: "b", kind: "arret", name: "Centre", coordinates: [6.125, 45.9] }], geometry: [[6.12, 45.9], [6.13, 45.9]], distanceM: 800, warnings: [], updatedAt: "2026-01-01" };
for (const width of [1440, 390]) test(`horaires créés et réouverture ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 });
  await page.route("https://tiles.openfreemap.org/styles/liberty", (route) => route.fulfill({ json: { version: 8, sources: {}, layers: [{ id: "background", type: "background", paint: { "background-color": "#e5eee8" } }] } }));
  await page.route("**/data/sibra.json", (route) => route.fulfill({ json: { metadata: { sourceUrl: "fixture", attribution: "fixture", license: "fixture", validFrom: "2026-01-01", validTo: "2026-12-31", generatedAt: "2026-01-01" }, lines: [] } }));
  await page.route("**/data/sibra-schedule.json", (route) => route.fulfill({ json: { metadata: { validFrom: "2026-01-01", validTo: "2026-12-31", timeZone: "Europe/Paris" }, serviceDates: {}, trips: [] } }));
  await page.addInitScript((value) => localStorage.setItem("yft.bus-created-lines.v1", JSON.stringify([value])), line);
  await page.goto("/");
  await expect(page.locator(".map canvas")).toBeVisible();
  await page.getByRole("button", { name: "Menu Bus" }).click();
  await page.getByText("Créer ou modifier les horaires").click();
  const editor = page.getByRole("region", { name: "Éditeur d’horaires" });
  await editor.getByLabel("Origine").selectOption("created");
  await editor.getByRole("combobox", { name: "Ligne", exact: true }).selectOption("c1");
  await editor.getByLabel("Parcours et sens").selectOption("c1");
  await editor.getByLabel("Centre · minutes depuis le départ").fill("10");
  await editor.getByLabel("Arrivée · minutes depuis le départ").fill("20");
  await editor.getByLabel(/Départ au terminus/).fill("23:55");
  await editor.getByRole("button", { name: "Enregistrer le départ" }).click();
  await expect(editor.getByText("Centre : 24:05 (lendemain)")).toBeVisible();
  await editor.getByRole("button", { name: "Enregistrer le départ" }).click();
  await expect(editor.getByText(/Un départ existe déjà/)).toBeVisible();
  await editor.getByLabel("Jour de service").fill("2025-12-31");
  await editor.getByLabel(/Départ au terminus/).fill("47:55");
  await editor.getByRole("button", { name: "Enregistrer le départ" }).click();
  await expect(editor.getByText(/autre jour de service/)).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Menu Bus" }).click();
  await page.getByText("Créer ou modifier les horaires").click();
  await editor.getByLabel("Origine").selectOption("created");
  await editor.getByRole("combobox", { name: "Ligne", exact: true }).selectOption("c1");
  await editor.getByLabel("Parcours et sens").selectOption("c1");
  await expect(editor.getByText("Centre : 24:05 (lendemain)")).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("yft.bus-created-lines.v1")!)[0].name)).toBe("Test");
});

test("une course GTFS est décalée sans changer la référence", async ({ page }) => {
  const stopA = { id: "a", name: "Départ", coordinates: [6.12, 45.9] };
  const stopB = { id: "b", name: "Arrivée", coordinates: [6.13, 45.9] };
  const trip = { id: "t", lineId: "1", variantId: "v", directionId: "0", serviceId: "s", stops: [{ stopId: "a", arrival: 86340, departure: 86340, progress: 0 }, { stopId: "b", arrival: 86760, departure: 86760, progress: 1 }] };
  await page.route("https://tiles.openfreemap.org/styles/liberty", (route) => route.fulfill({ json: { version: 8, sources: {}, layers: [{ id: "background", type: "background", paint: { "background-color": "#e5eee8" } }] } }));
  await page.route("**/data/sibra.json", (route) => route.fulfill({ json: { metadata: { sourceUrl: "fixture", attribution: "fixture", license: "fixture", validFrom: "2026-01-01", validTo: "2026-12-31", generatedAt: "2026-01-01" }, lines: [{ id: "1", shortName: "1", longName: "Test", color: "#004433", variants: [{ id: "v", headsign: "Arrivée", coordinates: [stopA.coordinates, stopB.coordinates], stops: [stopA, stopB] }] }] } }));
  await page.route("**/data/sibra-schedule.json", (route) => route.fulfill({ json: { metadata: { validFrom: "2026-01-01", validTo: "2026-12-31", timeZone: "Europe/Paris" }, serviceDates: { "2026-01-01": ["s"] }, trips: [trip] } }));
  await page.goto("/");
  await expect(page.locator(".map canvas")).toBeVisible();
  await page.getByRole("button", { name: "Menu Bus" }).click();
  await page.getByText("Créer ou modifier les horaires").click();
  const editor = page.getByRole("region", { name: "Éditeur d’horaires" });
  await editor.getByRole("combobox", { name: "Ligne", exact: true }).selectOption("1");
  await editor.getByRole("combobox", { name: "Parcours et sens" }).selectOption("v");
  await editor.getByRole("combobox", { name: "Course de référence" }).selectOption("t");
  await editor.getByLabel(/Départ au terminus/).fill("24:01");
  await editor.getByRole("button", { name: "Enregistrer le départ" }).click();
  await expect(editor.getByText("Arrivée : 24:08 (lendemain)")).toBeVisible();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("yft.bus-terminus-schedules.v1")!));
  expect(stored.entries[0].tripId).toBe("t");
  expect(trip.stops[0].departure).toBe(86340);
});
